<?php

namespace Gemboot\Notifications;

use NotificationChannels\Telegram\TelegramMessage;
use Illuminate\Notifications\Notification;

/**
 * @deprecated since 8.8, removed in 9.0. Use Laravel notifications with the
 *             laravel-notification-channels/telegram package directly, or a log channel.
 */
class Telegram extends Notification
{
    public function via($notifiable)
    {
        return ["telegram"];
    }

    public function toTelegram($notifiable)
    {
        if (app('config')->get('gemboot.notifications.enable')) {
            $telegram_user_id = app('config')->get('gemboot.notifications.telegram.chat_id');
            $content = $notifiable->content;

            return TelegramMessage::create()
                // Optional recipient user id.
                ->to($telegram_user_id)
                // Markdown supported.
                ->content($content)
                ->line("")
                ->line("_generated by gemboot-lara_");
        } else {
            return null;
        }
    }
}
